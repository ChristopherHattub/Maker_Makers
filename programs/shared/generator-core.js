        var sH = slider('Stretch height', 40, 250, 5, function () { return curS(1); }, function (v) { setScale(1, v); }, pct, done);
        var sD = slider('Stretch width', 40, 250, 5, function () { return curS(2); }, function (v) { setScale(2, v); }, pct, done);
